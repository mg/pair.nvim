local edit = require("pair.edit")

local function reset(lines)
  edit.dismiss_answer()
  if edit.pending() then edit.accept() end
  vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)
end

reset({ "alpha", "beta", "gamma" })
vim.api.nvim_win_set_cursor(0, { 2, 1 })
vim.cmd("normal! v2l\27")
local selected = assert(edit.selection())
assert(selected.original == "eta", "character selection should capture exact text")
assert(edit.show(selected, "ETA"))
assert(vim.api.nvim_buf_get_lines(0, 1, 2, false)[1] == "bETA", "proposal should appear in the unsaved buffer immediately")
local control_ns = vim.api.nvim_get_namespaces()["pair.nvim.control"]
local controls = vim.api.nvim_buf_get_extmarks(0, control_ns, 0, -1, { details = true })
assert(#controls == 1 and controls[1][4].virt_lines_above, "proposal controls should appear above the changed code")
assert(#vim.api.nvim_list_wins() == 1, "proposal controls should not open a floating window")
assert(vim.api.nvim_win_get_cursor(0)[1] == 1, "cursor should stay above the changed code")
assert(edit.accept())
assert(#vim.api.nvim_buf_get_extmarks(0, control_ns, 0, -1, {}) == 0, "accept should remove controls")
assert(vim.api.nvim_buf_get_lines(0, 1, 2, false)[1] == "bETA", "accept should keep the proposal")

