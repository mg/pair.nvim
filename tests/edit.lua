-- Visual-mode ':' adds '<,'> to the command. Both selection commands must accept it.
local pair = require("pair")
pair.setup({ keymaps = false })
local asked, changed
pair.ask = function(message)
  asked = { message = message, target = assert(edit.selection()) }
end
pair.change = function(message)
  changed = { message = message, target = assert(edit.selection()) }
end
reset({ "alpha", "beta", "gamma" })
vim.api.nvim_win_set_cursor(0, { 1, 0 })
vim.cmd("normal! Vj\27")
vim.cmd("'<,'>PairAsk why is this here")
assert(asked.message == "why is this here" and asked.target.original == "alpha\nbeta", "PairAsk should accept a visual range")
vim.cmd("'<,'>PairChange simplify this")
assert(changed.message == "simplify this" and changed.target.original == "alpha\nbeta", "PairChange should accept a visual range")

